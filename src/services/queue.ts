// To write a dedicated, reusable function that takes an authenticated webhook payload and pushes it into Redis Streams (stream:webhooks:incoming) in under 1 millisecond.

import { redis } from './redis.js';
import type { QueuedEventData } from '../types/webhook.js';

// The centralized Redis Stream key for all incoming webhook traffic
export const WEBHOOK_STREAM_KEY = 'stream:webhooks:incoming';

/**
 * Pushes an authenticated webhook event into the durable Redis Stream.
 * Takes < 1 millisecond and guarantees global microsecond ordering.
 * 
 * @returns {Promise<string>} The unique microsecond Stream ID generated by Redis (e.g. "1732356500000-0")
 */
export async function pushToEventQueue(data: QueuedEventData): Promise<string> {
  const { eventId, provider, topic, entityId, payload } = data;

  // XADD stream_key * field1 value1 field2 value2 ...
  // '*' tells Redis: automatically generate a microsecond timestamp ID!
  const streamId = await redis.xadd(
    WEBHOOK_STREAM_KEY,
    '*',
    'eventId', eventId,
    'provider', provider,
    'topic', topic,
    'entityId', entityId || '',
    'payload', payload,
    'enqueuedAt', new Date().toISOString()
  );

  if (!streamId) {
    throw new Error('Failed to enqueue webhook: Redis stream returned null ID');
  }

  return streamId;
}

/**
 * Utility: Gets the current number of events waiting in the Redis Stream queue
 */
export async function getQueueLength(): Promise<number> {
  return await redis.xlen(WEBHOOK_STREAM_KEY);
}